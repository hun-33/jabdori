"""UI 리뷰용으로 지금 화면을 한 장씩 찍는다 (웹 흉내 모드, 390x844)."""
from playwright.sync_api import sync_playwright
OUT = '/tmp/review'
import os; os.makedirs(OUT, exist_ok=True)
errs = []
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    ctx = b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, has_touch=True, is_mobile=True, locale='ko-KR')
    pg = ctx.new_page()
    pg.on('pageerror', lambda e: errs.append(str(e)))
    shot = lambda n: pg.screenshot(path=f'{OUT}/{n}.png')
    ev = lambda c: pg.evaluate(c)
    pg.goto('file:///home/claude/jabdori-app/dist/index.html'); ev('localStorage.clear()'); pg.reload(); pg.wait_for_timeout(600)
    shot('01_login')
    pg.click('.btn-kakao'); pg.wait_for_timeout(1800); shot('02_consent')
    pg.click('[data-act=consentAgree]'); pg.wait_for_timeout(2200); shot('03_onb1')
    pg.click('[data-act=onbNext]'); pg.wait_for_timeout(400); shot('04_onb2')
    pg.click('[data-act=onbSkip]'); pg.wait_for_timeout(500); shot('05_today_empty')
    ev('ACT.cSeed()'); pg.wait_for_timeout(300); ev('ACT.cSeedExtra && ACT.cSeedExtra()'); pg.wait_for_timeout(300)
    ev('hideBanner && hideBanner()'); ev("document.querySelector('#console') && document.body.classList.remove('console-open')"); pg.wait_for_timeout(500)
    shot('06_today_seeded')
    ev("window.scrollTo(0,0); document.querySelector('#screen').scrollTop = 600"); pg.wait_for_timeout(300); shot('07_today_scrolled')
    ev("document.querySelector('#screen').scrollTop = 0"); pg.wait_for_timeout(200)
    t = pg.query_selector('.ticket [data-act=startOcc]')
    if t: t.click(); pg.wait_for_timeout(600); ev('hideBanner && hideBanner()'); pg.wait_for_timeout(300); shot('08_after_start')
    f = pg.query_selector('[data-act=openFocus]')
    if f: f.click(); pg.wait_for_timeout(700); shot('09_focus')
    ev("ACT.cTime({dataset:{hm:'19:50'}})"); ev('hideBanner && hideBanner()'); pg.wait_for_timeout(2500); ev('hideBanner && hideBanner()'); pg.wait_for_timeout(300); shot('10_focus_late')
    ev("ACT.cSlack({dataset:{app:'YouTube'}})"); pg.wait_for_timeout(700); shot('11_slack_popup')
    ev("ui.popup = null; render()"); pg.wait_for_timeout(300)
    x = pg.query_selector('[data-act=finishOcc]')
    if x: x.click(); pg.wait_for_timeout(1500); shot('12_result')
    ev("ui.result = null; ui.focusKey = null; ui.sheet = null; ui.tab = 'calendar'; render()"); pg.wait_for_timeout(600); shot('13_cal_default')
    for m in ['month', 'week', 'day']:
        el = pg.query_selector(f'[data-act=calMode][data-v={m}]')
        if el: el.click(); pg.wait_for_timeout(600); shot(f'14_cal_{m}')
    ev("ui.tab = 'records'; render()"); pg.wait_for_timeout(500); shot('15_records')
    ev("ui.tab = 'me'; render()"); pg.wait_for_timeout(500); shot('16_me_top')
    ev("document.querySelector('#screen').scrollTop = 900"); pg.wait_for_timeout(300); shot('17_me_mid')
    ev("document.querySelector('#screen').scrollTop = 99999"); pg.wait_for_timeout(300); shot('18_me_bottom')
    ev("ui.tab = 'today'; render()"); pg.wait_for_timeout(400)
    ev("ACT.openAdd({dataset:{date: today()}})"); pg.wait_for_timeout(600); shot('19_form_top')
    ev("const s=document.querySelector('#layer-sheet .sheet-body, #layer-sheet .sheet'); if(s) s.scrollTop = 700"); pg.wait_for_timeout(300); shot('20_form_mid')
    ev("const s=document.querySelector('#layer-sheet .sheet-body, #layer-sheet .sheet'); if(s) s.scrollTop = 99999"); pg.wait_for_timeout(300); shot('21_form_bottom')
    ev("ACT.formClose && ACT.formClose()"); pg.wait_for_timeout(400); ev("ui.sheet=null; render()"); pg.wait_for_timeout(300)
    m = pg.query_selector('[data-act=mascotTap]')
    if m: m.click(); pg.wait_for_timeout(700); shot('22_mascot_menu')
    b.close()
print('errors:', errs)
print(sorted(os.listdir(OUT)))
